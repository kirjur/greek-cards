def strip_accents(s):
	return "".join(c for c in unicodedata.normalize("NFD", s) if unicodedata.category(c) != "Mn")


def make_id(deck, el):
	base = strip_accents(el).lower().replace("ς", "σ")
	base = "".join(c if c.isalnum() else "-" for c in base).strip("-")
	while "--" in base:
		base = base.replace("--", "-")
	return f"{deck}:{base}"


def main(out):
	words, seen = [], set()

	def add(deck, lesson, w):
		w = dict(w)
		w["deck"], w["lesson"] = deck, lesson
		w["id"] = w.get("id") or make_id(deck, w["el"])
		if w["id"] in seen:
			# same spelling with different stress (e.g. ιώ twice) — keep the first
			return
		seen.add(w["id"])
		words.append({k: v for k, v in w.items() if v is not None})

	for lesson, rows in VOCAB.items():
		for w in rows:
			add("vocab", lesson, w)
	for lesson, rows in PHRASES.items():
		for w in rows:
			add("phrases", lesson, w)
	for lesson, rows in READING.items():
		for w in rows:
			add("reading", lesson, w)
	for el, ru in ALPHABET:
		add("rules", 1, W(el, ru, pos="letter"))
	for el, ru in DIGRAPHS:
		add("rules", 2, W(el, ru, pos="combo"))
	assert len(COMBOS) == len(ANSWERS) == 60, (len(COMBOS), len(ANSWERS))
	combo_seen = {el for el, _ in DIGRAPHS}
	for el, ru in zip(COMBOS, ANSWERS):
		if el in combo_seen:
			continue
		combo_seen.add(el)
		w = W(el, ru, pos="combo", note="Карточки дифтонгов и сочетаний (24.09).")
		w["id"] = f"rules:combo-{el}"
		add("rules", 3, w)

	data = {"version": 1, "lessons": LESSONS, "decks": DECKS, "words": words}
