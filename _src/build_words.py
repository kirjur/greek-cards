def strip_accents(s):
	return "".join(c for c in unicodedata.normalize("NFD", s) if unicodedata.category(c) != "Mn")


def make_id(deck, el):
	base = strip_accents(el).lower().replace("ς", "σ")
	base = "".join(c if c.isalnum() else "-" for c in base).strip("-")
	while "--" in base:
		base = base.replace("--", "-")
	return f"{deck}:{base}"


def main(out):
	words, seen = [], set()

	def add(deck, lesson, w):
		w = dict(w)
		w["deck"], w["lesson"] = deck, lesson
		w["id"] = w.get("id") or make_id(deck, w["el"])
		if w["id"] in seen:
			# same spelling with different stress (e.g. ιώ twice) — keep the first
			return
		seen.add(w["id"])
		words.append({k: v for k, v in w.items() if v is not None})

	for lesson, rows in VOCAB.items():
		for w in rows:
			add("vocab", lesson, w)
